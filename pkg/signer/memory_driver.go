package signer

import (
	"context"
	"crypto"
	"crypto/rand"
	"crypto/rsa"
	"crypto/sha256"
	"crypto/x509"
	"encoding/pem"
	"fmt"
	"os"
	"path/filepath"
	"sync"
)

// MemorySignDriver provides in-memory RSA cryptographic signing for testing and development environments.
type MemorySignDriver struct {
	mu      sync.RWMutex
	keys    map[string]*rsa.PrivateKey
	pubkeys map[string][]byte
}

func NewMemorySignDriver() *MemorySignDriver {
	return &MemorySignDriver{
		keys:    make(map[string]*rsa.PrivateKey),
		pubkeys: make(map[string][]byte),
	}
}

func (m *MemorySignDriver) getOrCreateKey(project string) (*rsa.PrivateKey, []byte, error) {
	m.mu.Lock()
	defer m.mu.Unlock()

	key, exists := m.keys[project]
	if exists {
		return key, m.pubkeys[project], nil
	}

	privKey, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return nil, nil, fmt.Errorf("failed generating rsa key: %w", err)
	}

	pubASN1, err := x509.MarshalPKIXPublicKey(&privKey.PublicKey)
	if err != nil {
		return nil, nil, fmt.Errorf("failed marshaling public key: %w", err)
	}

	pubPEM := pem.EncodeToMemory(&pem.Block{
		Type:  "PUBLIC KEY",
		Bytes: pubASN1,
	})

	m.keys[project] = privKey
	m.pubkeys[project] = pubPEM
	return privKey, pubPEM, nil
}

// PublicKey returns the PEM-encoded public key for the project.
func (m *MemorySignDriver) PublicKey(_ context.Context, opts SignOptions) ([]byte, error) {
	_, pub, err := m.getOrCreateKey(opts.Project)
	if err != nil {
		return nil, err
	}
	return pub, nil
}

// SignDetached signs data using RSA-PKCS1v15 and SHA-256.
func (m *MemorySignDriver) SignDetached(_ context.Context, data []byte, opts SignOptions) ([]byte, error) {
	priv, _, err := m.getOrCreateKey(opts.Project)
	if err != nil {
		return nil, err
	}

	h := sha256.Sum256(data)
	sig, err := rsa.SignPKCS1v15(rand.Reader, priv, crypto.SHA256, h[:])
	if err != nil {
		return nil, fmt.Errorf("rsa sign failed: %w", err)
	}

	return pem.EncodeToMemory(&pem.Block{
		Type:  "SIGNATURE",
		Bytes: sig,
	}), nil
}

// SignClearsign generates a cleartext signed document.
func (m *MemorySignDriver) SignClearsign(_ context.Context, data []byte, opts SignOptions) ([]byte, error) {
	sig, err := m.SignDetached(context.Background(), data, opts)
	if err != nil {
		return nil, err
	}
	return append(data, append([]byte("\n-----BEGIN SIGNATURE-----\n"), sig...)...), nil
}

// SignRPM creates a simulated RPM signature for testing.
func (m *MemorySignDriver) SignRPM(_ context.Context, rpmPath string, opts SignOptions) error {
	cleanPath := filepath.Clean(rpmPath)
	// #nosec G304 -- reading sanitized rpm path for testing signature
	data, err := os.ReadFile(cleanPath)
	if err != nil {
		return err
	}
	sig, err := m.SignDetached(context.Background(), data, opts)
	if err != nil {
		return err
	}
	// Append signature marker to test file
	// #nosec G304 -- appending signature to sanitized test rpm path
	f, err := os.OpenFile(cleanPath, os.O_APPEND|os.O_WRONLY, 0600)
	if err != nil {
		return err
	}
	defer f.Close()
	_, err = f.Write(append([]byte("\n[BSGO_SIGNED_RPM]"), sig...))
	return err
}

// VerifyDetached verifies a detached signature generated by MemorySignDriver.
func (m *MemorySignDriver) VerifyDetached(pubKeyPEM, data, sigPEM []byte) error {
	return VerifyRSADetached(pubKeyPEM, data, sigPEM)
}
